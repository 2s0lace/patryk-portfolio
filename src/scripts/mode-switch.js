const modeButtons = document.querySelectorAll("[data-mode-target]");
const localeButtons = document.querySelectorAll("[data-locale-target]");
const sectionButtons = document.querySelectorAll("[data-section-target]");
const themeButtons = document.querySelectorAll("[data-theme-target]");
const modeOnlyElements = document.querySelectorAll("[data-mode-only]");
const modeToast = document.querySelector("#mode-toast");
const aiChatSend = document.querySelector("#ai-chat-send");
const aiChatOutput = document.querySelector("#ai-chat-output");
const aiChatThinking = document.querySelector("#ai-chat-thinking");
const aiChatResponse = document.querySelector("#ai-chat-response");
const aiChatDiamond = document.querySelector(".ai-chat-diamond");
const aiChatStatus = document.querySelector("#ai-chat-status");
const sectionKeys = [...sectionButtons].map((button) => button.dataset.sectionTarget);
const sectionLinks = document.querySelectorAll("[data-section-link]");
const availableSectionsByMode = {
  patryk: sectionKeys,
  "2s0lace": ["section3", "section6"],
};
const storedSection = localStorage.getItem("portfolio-section");
const defaultSection = sectionKeys.includes(storedSection) ? storedSection : "section2";

const state = {
  mode: document.body.dataset.mode || "patryk",
  locale: document.documentElement.lang === "en" ? "en" : "pl",
  theme: document.documentElement.dataset.theme === "dark" ? "dark" : "light",
  activeSection: defaultSection,
};

function getTranslation(key) {
  const [scope, name] = key.includes(".") ? key.split(".") : [state.mode, key];
  return translations[state.locale]?.[scope]?.[name] ?? translations.pl?.[scope]?.[name] ?? null;
}

function applyTranslations() {
  document.documentElement.lang = state.locale;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = getTranslation(element.dataset.i18n);
    if (value !== null) element.textContent = value;
  });

  document.querySelectorAll("[data-i18n-attr]").forEach((element) => {
    element.dataset.i18nAttr.split(";").forEach((rule) => {
      const separator = rule.indexOf(":");
      if (separator === -1) return;
      const attribute = rule.slice(0, separator);
      const value = getTranslation(rule.slice(separator + 1));
      if (value !== null) element.setAttribute(attribute, value);
    });
  });

  modeButtons.forEach((button) => {
    button.classList.toggle("is-active", button.dataset.modeTarget === state.mode);
    button.setAttribute("aria-pressed", String(button.dataset.modeTarget === state.mode));
  });

  modeOnlyElements.forEach((element) => {
    const isVisible = element.dataset.modeOnly === state.mode;
    element.toggleAttribute("hidden", !isVisible);
    element.setAttribute("aria-hidden", String(!isVisible));
  });

  localeButtons.forEach((button) => {
    button.classList.toggle("is-active", button.dataset.localeTarget === state.locale);
    button.setAttribute("aria-pressed", String(button.dataset.localeTarget === state.locale));
  });

  themeButtons.forEach((button) => {
    button.classList.toggle("is-active", button.dataset.themeTarget === state.theme);
    button.setAttribute("aria-pressed", String(button.dataset.themeTarget === state.theme));
  });

  document.title = translations[state.locale]?.[state.mode]?.title || document.title;
}

function applySections() {
  const availableSections = availableSectionsByMode[state.mode] || sectionKeys;

  if (!availableSections.includes(state.activeSection)) {
    state.activeSection = availableSections[0];
  }

  sectionButtons.forEach((button) => {
    const sectionKey = button.dataset.sectionTarget;
    const isAvailable = availableSections.includes(sectionKey);
    const isActive = isAvailable && sectionKey === state.activeSection;
    const target = document.getElementById(button.getAttribute("aria-controls"));

    button.classList.toggle("is-locked", !isAvailable);
    button.setAttribute("aria-disabled", String(!isAvailable));
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
    target?.classList.toggle("is-hidden", !isActive);
    target?.setAttribute("aria-hidden", String(!isActive));
  });

  localStorage.setItem("portfolio-section", state.activeSection);
}

let modeToastTimeout;

function hideModeToast() {
  if (!modeToast) return;
  window.clearTimeout(modeToastTimeout);
  modeToast.hidden = true;
  modeToast.classList.remove("is-visible");
}

function showModeToast() {
  if (!modeToast) return;
  window.clearTimeout(modeToastTimeout);
  modeToast.hidden = false;
  modeToast.classList.remove("is-visible");
  requestAnimationFrame(() => modeToast.classList.add("is-visible"));
  modeToastTimeout = window.setTimeout(() => {
    modeToast.classList.remove("is-visible");
    modeToast.hidden = true;
  }, 2400);
}

function resetAiChat() {
  aiGeneration += 1;
  aiChatHasGenerated = false;
  window.clearTimeout(aiThinkingTimeout);
  window.clearTimeout(aiTypingTimeout);
  aiChatOutput?.setAttribute("hidden", "true");
  aiChatThinking?.removeAttribute("hidden");
  aiChatThinking?.classList.remove("is-done");
  aiChatDiamond?.removeAttribute("hidden");
  if (aiChatStatus) {
    aiChatStatus.textContent = getTranslation("aboutAiThinking") || "Thinking";
  }
  aiChatResponse?.setAttribute("hidden", "true");
  if (aiChatResponse) aiChatResponse.textContent = "";
  aiChatSend?.removeAttribute("disabled");
  aiChatSend?.setAttribute("aria-expanded", "false");
}

let aiThinkingTimeout;
let aiTypingTimeout;
let aiGeneration = 0;
let aiChatHasGenerated = false;

function typeAiResponse(tokens, generation, index = 0) {
  if (!aiChatResponse || generation !== aiGeneration) return;
  if (index >= tokens.length) {
    aiChatThinking?.removeAttribute("hidden");
    aiChatThinking?.classList.add("is-done");
    aiChatDiamond?.setAttribute("hidden", "true");
    if (aiChatStatus) {
      aiChatStatus.textContent = getTranslation("aboutAiDone") || "Done";
    }
    aiChatHasGenerated = true;
    aiChatSend?.removeAttribute("disabled");
    return;
  }

  aiChatResponse.textContent += tokens[index];
  aiTypingTimeout = window.setTimeout(
    () => typeAiResponse(tokens, generation, index + 1),
    54,
  );
}

function typeAiStopMessage(tokens, generation, index = 0) {
  if (!aiChatResponse || generation !== aiGeneration) return;
  if (index >= tokens.length) return;

  aiChatResponse.textContent += tokens[index];
  aiTypingTimeout = window.setTimeout(
    () => typeAiStopMessage(tokens, generation, index + 1),
    54,
  );
}

aiChatSend?.addEventListener("click", () => {
  if (!aiChatOutput || !aiChatThinking || !aiChatResponse) return;

  if (aiChatHasGenerated) {
    aiGeneration += 1;
    const generation = aiGeneration;
    const stopMessage = getTranslation("aboutAiStopMessage") || "Stop wasting compute and check the portfolio!";
    const stopTokens = stopMessage.match(/\S+\s*/g) || [];

    window.clearTimeout(aiThinkingTimeout);
    window.clearTimeout(aiTypingTimeout);
    aiChatOutput.removeAttribute("hidden");
    aiChatThinking.setAttribute("hidden", "true");
    aiChatResponse.removeAttribute("hidden");
    aiChatResponse.textContent = "";
    aiChatSend.setAttribute("aria-expanded", "true");
    aiChatSend.setAttribute("disabled", "true");
    typeAiStopMessage(stopTokens, generation);
    return;
  }

  aiGeneration += 1;
  const generation = aiGeneration;
  const response = getTranslation("aboutAiResponse") || "2s0lace is an independent graphic design and multimedia art project.";
  const tokens = response.match(/\S+\s*/g) || [];

  window.clearTimeout(aiThinkingTimeout);
  window.clearTimeout(aiTypingTimeout);
  aiChatOutput?.removeAttribute("hidden");
  aiChatThinking.removeAttribute("hidden");
  aiChatResponse.setAttribute("hidden", "true");
  aiChatResponse.textContent = "";
  aiChatSend.setAttribute("aria-expanded", "true");
  aiChatSend.setAttribute("disabled", "true");

  aiThinkingTimeout = window.setTimeout(() => {
    if (generation !== aiGeneration) return;
    aiChatThinking.setAttribute("hidden", "true");
    aiChatResponse.removeAttribute("hidden");
    typeAiResponse(tokens, generation);
  }, 820);
});

function setMode(mode) {
  if (!translations[state.locale]?.[mode]) return;
  state.mode = mode;
  document.body.dataset.mode = mode;
  document.documentElement.style.setProperty(
    "--accent",
    mode === "2s0lace" ? "#d2f28a" : "#d9ff55",
  );
  applyTranslations();
  applySections();
  hideModeToast();
  resetAiChat();
}

function setLocale(locale) {
  if (!translations[locale]) return;
  state.locale = locale;
  localStorage.setItem("portfolio-locale", locale);
  applyTranslations();
  resetAiChat();
}

function setTheme(theme) {
  state.theme = theme === "dark" ? "dark" : "light";
  document.documentElement.dataset.theme = state.theme;
  localStorage.setItem("portfolio-theme", state.theme);
  applyTranslations();
}

modeButtons.forEach((button) => {
  button.addEventListener("click", () => setMode(button.dataset.modeTarget));
});

localeButtons.forEach((button) => {
  button.addEventListener("click", () => setLocale(button.dataset.localeTarget));
});

themeButtons.forEach((button) => {
  button.addEventListener("click", () => setTheme(button.dataset.themeTarget));
});

sectionButtons.forEach((button) => {
  button.addEventListener("click", () => {
    const availableSections = availableSectionsByMode[state.mode] || sectionKeys;
    if (!availableSections.includes(button.dataset.sectionTarget)) {
      showModeToast();
      return;
    }

    state.activeSection = button.dataset.sectionTarget;
    applySections();

    document.getElementById(button.getAttribute("aria-controls"))?.scrollIntoView({
      behavior: "smooth",
      block: "start",
    });
  });
});

sectionLinks.forEach((link) => {
  link.addEventListener("click", (event) => {
    const sectionKey = link.dataset.sectionLink;
    const availableSections = availableSectionsByMode[state.mode] || sectionKeys;

    if (!availableSections.includes(sectionKey)) {
      event.preventDefault();
      showModeToast();
      return;
    }

    const sectionButton = [...sectionButtons].find(
      (button) => button.dataset.sectionTarget === sectionKey,
    );
    sectionButton?.click();
  });
});

setMode(state.mode);
setLocale(state.locale);
setTheme(state.theme);
applySections();
